def calcular_doble(numero):
    doble = numero * 2
    print("El doble es:", doble)


def calcular_total(precio, cantidad):
    total = precio * cantidad
    print("El total a pagar es:", total)


def mostrar_mascota(nombre, tipo):
    print("Mi mascota se llama", nombre, "y es un", tipo)


# Llamadas a las funciones
calcular_doble(7)
calcular_total(35, 4)
mostrar_mascota("Rocky", "perro")